# ==========================================================
# FUNZIONE: LETTURA IMMAGINE DA FILE TXT
# ==========================================================
def read_image(file_path, expected_size=4096):
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File non trovato: {file_path}")

    with open(file_path, 'r') as file:
        data_array = np.loadtxt(file)

    if data_array.size != expected_size:
        raise ValueError(f"Il file {file_path} contiene {data_array.size} valori invece di {expected_size}.")

    # Ridimensionamento del vettore 1D in matrice 2D 64x64
    data = data_array.reshape((64, 64))
    print(f'Immagine caricata: {data.shape}')
    return data

# ==========================================================
# FUNZIONE: CONVOLUZIONE 2D CON ZERO PADDING
# ==========================================================
def convolve2d(image, kernel):
    """
    Applica una convoluzione 2D con kernel 3x3 e zero padding.
    """
    # Flip del kernel (convoluzione matematica)
    kernel = np.flipud(np.fliplr(kernel))

    # Output inizializzato a zero
    output = np.zeros_like(image, dtype=np.float32)

    # Zero padding sui bordi
    image_padded = np.pad(image, pad_width=1, mode='constant', constant_values=0)

    # Scansione pixel per pixel
    for y in range(image.shape[0]):
        for x in range(image.shape[1]):
            region = image_padded[y:y+3, x:x+3]
            output[y, x] = np.sum(region * kernel)

    return output

