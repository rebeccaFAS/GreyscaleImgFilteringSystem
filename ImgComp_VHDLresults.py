gray_scale_image_matrix = None  # Immagine originale (caricata da file TXT)
filtered_image_project = None   # Immagine filtrata (caricata da file TXT)

# ==========================================================
# FUNZIONE: CALCOLO SSIM E DSSIM
# ==========================================================
def ssim_calculation():
    """
    Questa funzione calcola i parametri relativi alla Structural Similarity.
    """
    global gray_scale_image_matrix
    global filtered_image_project

    if gray_scale_image_matrix is None or filtered_image_project is None:
        raise ValueError("Immagini non caricate. Chiama main_visualization prima.")

    # Calcolo SSIM
    ssimval, ssimmap = ssim(gray_scale_image_matrix, filtered_image_project, data_range=255, full=True)

    # Visualizzazione (subplot 2x2)
    plt.subplot(2, 2, 3)
    plt.imshow(ssimmap, cmap='gray')
    plt.title(f"SSIM Value: {ssimval:.4f}")
    plt.colorbar()

    # Calcolo DSSIM
    dssimval = (1 - ssimval) / 2
    dssimmap = (1 - ssimmap) / 2

    plt.subplot(2, 2, 4)
    plt.imshow(dssimmap, cmap='gray')
    #DSSIM Map with Global
    plt.title(f"DSSIM Value: {dssimval:.4f}")
    plt.colorbar()

    return ssimval, ssimmap, dssimval, dssimmap

# ==========================================================
# FUNZIONE: CALCOLO PSNR E SNR
# ==========================================================
def psnr_calculation():
    """
    Questa funzione calcola i parametri relativi al Peak Signal-to-Noise-Ratio.
    """
    global gray_scale_image_matrix
    global filtered_image_project

    if gray_scale_image_matrix is None or filtered_image_project is None:
        raise ValueError("Immagini non caricate. Chiama main_visualization prima.")

    # Calcolo PSNR
    psnr_i_f = peak_signal_noise_ratio(gray_scale_image_matrix, filtered_image_project, data_range=255)

    # Calcolo SNR manuale (basato su varianza segnale e rumore)
    signal_var = np.var(gray_scale_image_matrix.astype(float))
    noise_var = np.var((gray_scale_image_matrix - filtered_image_project).astype(float))
    if noise_var == 0:
        snr_i_f = float('inf')  # Evita divisione per zero
    else:
        snr_i_f = 10 * math.log10(signal_var / noise_var)

    # Visualizzazione (subplot 2x2)
    plt.subplot(2, 2, 2)
    plt.imshow(filtered_image_project, cmap='gray', vmin=0, vmax=255)
    plt.title(f"peaksnr: {psnr_i_f:.2f}, snr: {snr_i_f:.2f}")
    plt.colorbar()

    return psnr_i_f, snr_i_f

# ==========================================================
# FUNZIONE PRINCIPALE: VISUALIZZAZIONE E CALCOLO METRICHE
# ==========================================================
def main_visualization(input_file_path, filtered_file_path):
    global gray_scale_image_matrix, filtered_image_project

    # Caricamento immagini da file TXT
    gray_scale_image_matrix = read_image(input_file_path)  # Originale
    filtered_image_project = read_image(filtered_file_path)  # Filtrata

    # Calcolo valori
    psnr_val, snr_val = psnr_calculation()
    ssim_val, ssim_map, dssim_val, dssim_map = ssim_calculation()

    # Completamento visualizzazione
    plt.subplot(2, 2, 1)
    plt.imshow(gray_scale_image_matrix, cmap='gray', vmin=0, vmax=255)
    plt.title("Immagine Originale")
    plt.colorbar()

    plt.tight_layout()
    plt.show()

    # Stampa valori calcolati in console
    print(f"PSNR: {psnr_val:.2f}")
    print(f"SNR: {snr_val:.2f}")
    print(f"SSIM: {ssim_val:.4f}")
    print(f"DSSIM: {dssim_val:.4f}")

# ==========================================================
# CHIAMATA FINALE PER ESEGUIRE TUTTO
# ==========================================================
