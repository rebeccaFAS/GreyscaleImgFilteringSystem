# CALCOLO ERRORE ASSOLUTO
# ==========================================================
def ErroreAssoluto(file_path1, file_path2, output_file='errore_assoluto.txt', show_plot=True):
    img1 = read_image(file_path1)
    img2 = read_image(file_path2)
    errore_assoluto = np.abs(img1 - img2)
    np.savetxt(output_file, errore_assoluto.flatten(), fmt='%d')
    print(f'Errore assoluto salvato in: {output_file}')
    if show_plot:
        plt.figure(figsize=(8, 6))
        plt.imshow(errore_assoluto, cmap='viridis', vmin=0, vmax=500)
        plt.colorbar(label='Differenza Assoluta (pixel value)')
        plt.title('Mappa Errore Assoluto |Img1 - Img2|')
        plt.axis('off')
        plt.figtext(0.5, 0.02,
                    'Legenda: Viola = Coincidenza (errore 0), Giallo = Differenze alte (fino a 500)',
                    ha='center', fontsize=10, style='italic')
        plt.savefig('errore_assoluto_plot.png')
        plt.show()
        print('Grafico dell\'errore assoluto salvato come: errore_assoluto_plot.png')
    return errore_assoluto

